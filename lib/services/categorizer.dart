  static RegExp _compile(List<String> terms) {
    final alternation = terms.map(RegExp.escape).join('|');
    return RegExp(
      '(?<![a-z0-9])(?:$alternation)(?![a-z0-9])',
      caseSensitive: false,
    );
  }

  /// Normalizes a merchant name so near-identical SMS spellings share a key:
  /// lowercase, punctuation removed, tokens containing digits (store / terminal
  /// numbers) dropped.
  static String merchantKey(String merchant) {
    final tokens = merchant
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), ' ')
        .split(' ')
        .where((t) => t.isNotEmpty && !RegExp(r'\d').hasMatch(t));
    return tokens.join(' ');
  }

  /// Looks up a user-chosen category. An exact key match wins; otherwise the
  /// longest stored key that is a whole-word prefix of [merchant] (or the
  /// other way round) applies, so "Swiggy" also covers "Swiggy Bangalore".
  static SpendCategory? learnedCategory(
    Map<String, SpendCategory> learned,
    String merchant,
  ) {
    if (learned.isEmpty) return null;
    final key = merchantKey(merchant);
    if (key.isEmpty) return null;
    final exact = learned[key];
    if (exact != null) return exact;
    String? best;
    for (final k in learned.keys) {
      final related = key.startsWith('$k ') || k.startsWith('$key ');
      if (related && (best == null || k.length > best.length)) best = k;
    }
    return best == null ? null : learned[best];
  }

  /// Categorise using the merchant name first, then the wider message text.
  static SpendCategory categorize(String merchant, [String context = '']) {
    for (final text in [merchant, context]) {
      if (text.trim().isEmpty) continue;
      for (final (category, pattern) in _rules) {
        if (pattern.hasMatch(text)) return category;
      }
    }
    return SpendCategory.other;
  }
